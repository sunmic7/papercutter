"""Client-side exchange with the PaperFlow online-review beta.

This module never calls a delivery exporter.  It creates a disposable review
snapshot from locally confirmed pages, uploads scaled page previews for human
inspection, and writes returned page decisions beside the local project.  The
actual cropped images and delivery JSON remain generated by PaperFlow locally.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from review_tools import manual_annotation_data as annotation_data


SCHEMA_VERSION = 1
DEFAULT_MAX_PREVIEW_SIDE = 1600
DECISIONS_FILENAME = "PaperFlow在线审核决定.json"


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _page_entries(project: dict, max_preview_side: int, include_previews: bool) -> list[dict]:
    try:
        import cv2
        import numpy as np
    except ImportError as error:  # pragma: no cover - installed with PaperFlow
        raise RuntimeError("本机缺少 OpenCV，无法生成审核预览。") from error
    entries: list[dict] = []
    for kind, pages_key, records_key, answer in (
        ("question", "pages", "questions", False),
        ("answer", "answer_pages", "answers", True),
    ):
        for page_index, page in enumerate(project.get(pages_key, [])):
            # A review submission is deliberately a snapshot of confirmed work,
            # rather than a live copy of draft frames that may still change.
            if str(page.get("status", "")) != "accepted":
                continue
            regions = []
            for record in page.get(records_key, []):
                if not isinstance(record, dict) or str(record.get("region_role", "question")) != "question":
                    continue
                bbox = record.get("bbox")
                if not (isinstance(bbox, (list, tuple)) and len(bbox) == 4):
                    continue
                regions.append({
                    "id": str(record.get("id", "")),
                    "display_number": annotation_data.display_number(record),
                    "bbox": [int(round(float(value))) for value in bbox],
                })
            if not regions:
                continue
            source = annotation_data.source_path(project, page, answer)
            # cv2.imread is unreliable on Windows when the textbook path has
            # Chinese characters.  PaperFlow's normal page workflow uses
            # fromfile + imdecode for the same reason, so keep review preview
            # generation consistent with it.
            try:
                image = cv2.imdecode(np.fromfile(str(source), dtype=np.uint8), cv2.IMREAD_COLOR)
            except OSError:
                image = None
            if image is None:
                raise ValueError(f"无法读取本地页面，不能提交审核：{source}")
            height, width = image.shape[:2]
            item = {
                "page_key": f"{kind}-{page_index}",
                "kind": kind,
                "page_index": page_index,
                "image_name": str(page.get("image", Path(source).name)),
                "width": int(width),
                "height": int(height),
                "regions": regions,
            }
            if include_previews:
                scale = min(1.0, float(max_preview_side) / max(width, height))
                if scale < 1.0:
                    image = cv2.resize(image, (max(1, round(width * scale)), max(1, round(height * scale))), interpolation=cv2.INTER_AREA)
                ok, encoded = cv2.imencode(".jpg", image, [int(cv2.IMWRITE_JPEG_QUALITY), 78])
                if not ok:
                    raise RuntimeError(f"无法压缩审核预览：{source}")
                item["preview"] = "data:image/jpeg;base64," + base64.b64encode(encoded.tobytes()).decode("ascii")
            entries.append(item)
    return entries


def build_review_snapshot(project_path: str | Path, max_preview_side: int = DEFAULT_MAX_PREVIEW_SIDE, *, include_previews: bool = True) -> dict:
    """Build a review-only document without touching any delivery output."""
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    pages = _page_entries(project, max(480, int(max_preview_side)), include_previews)
    if not pages:
        raise ValueError("没有包含题框的已确认页面，无法提交审核。")
    book_root = Path(str(project.get("book_root") or project.get("image_root") or project_path.parent))
    book_id = str(project.get("delivery_book_id", "")).strip() or hashlib.sha256(str(project_path).encode("utf-8")).hexdigest()[:20]
    identity_pages = [{key: value for key, value in page.items() if key != "preview"} for page in pages]
    fingerprint = hashlib.sha256(_canonical_json({"book_id": book_id, "pages": identity_pages})).hexdigest()
    return {
        "schema_version": SCHEMA_VERSION,
        "kind": "paperflow_page_review_snapshot",
        "book": {"id": book_id, "name": book_root.name or project_path.parent.name},
        "project_revision": int(project.get("project_revision", 0)),
        "snapshot_fingerprint": fingerprint,
        "pages": pages,
        "notice": "仅为审核预览；最终裁图和最终 JSON 未上传，且必须在本地生成。",
    }


def _request_json(url: str, method: str = "GET", payload: dict | None = None, token: str = "", timeout: int = 120) -> dict:
    headers = {"Accept": "application/json"}
    body = None
    if payload is not None:
        body = _canonical_json(payload)
        headers["Content-Type"] = "application/json; charset=utf-8"
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = Request(url, data=body, headers=headers, method=method)
    try:
        with urlopen(request, timeout=timeout) as response:
            data = json.loads(response.read().decode("utf-8"))
    except HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")
        try:
            detail = json.loads(detail).get("error", detail)
        except json.JSONDecodeError:
            pass
        raise RuntimeError(f"审核中心拒绝请求：{detail}") from error
    except URLError as error:
        raise RuntimeError(f"无法连接审核中心：{error.reason}") from error
    if not isinstance(data, dict) or not data.get("ok"):
        raise RuntimeError(str(data.get("error", "审核中心响应无效")) if isinstance(data, dict) else "审核中心响应无效")
    return data


def _base_url(value: str) -> str:
    value = str(value or "").strip().rstrip("/")
    if not value.startswith(("http://", "https://")):
        raise ValueError("审核中心地址必须以 http:// 或 https:// 开头。")
    return value


def build_project_sync_snapshot(project_path: str | Path) -> dict:
    """Build the account-owned project document sent to the company server.

    This contains annotation records, but strips the local textbook locations.
    It is separate from review previews and is never a final-delivery export.
    """
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    # Round-trip through JSON to avoid mutating the in-memory project that the
    # desktop bridge is currently using.
    portable = json.loads(json.dumps(project, ensure_ascii=False))
    for key in ("book_root", "image_root", "answer_image_root"):
        portable.pop(key, None)
    book_id = str(portable.get("delivery_book_id", "")).strip()
    if not book_id:
        raise ValueError("本地工程缺少公司教材编号，不能同步到员工目录。")
    metadata = portable.get("book_metadata") if isinstance(portable.get("book_metadata"), dict) else {}
    book_name = str(metadata.get("book_name") or project_path.parent.name).strip()
    return {
        "schema_version": SCHEMA_VERSION,
        "kind": "paperflow_project_sync",
        "book": {"id": book_id, "name": book_name},
        "project": portable,
    }


def submit_review_snapshot(server_url: str, username: str, password: str, project_path: str | Path, max_preview_side: int = DEFAULT_MAX_PREVIEW_SIDE) -> dict:
    """Sync the employee project, then upload review evidence; never final outputs."""
    base_url = _base_url(server_url)
    login = _request_json(base_url + "/api/login", "POST", {"username": username, "password": password}, timeout=30)
    project_sync = _request_json(
        base_url + "/api/projects/sync", "POST", build_project_sync_snapshot(project_path), login["token"], timeout=300
    )
    snapshot = build_review_snapshot(project_path, max_preview_side, include_previews=True)
    result = _request_json(base_url + "/api/submissions", "POST", snapshot, login["token"], timeout=300)
    return {
        "submission": result["submission"],
        "project": project_sync["project"],
        "snapshot_fingerprint": snapshot["snapshot_fingerprint"],
        "page_count": len(snapshot["pages"]),
    }


def upload_final_delivery(server_url: str, username: str, password: str, project_path: str | Path, delivery_path: str | Path) -> dict:
    """Upload a locally generated final package file-by-file under the account."""
    project = annotation_data.load_project(Path(project_path).resolve())
    book_id = str(project.get("delivery_book_id", "")).strip()
    root = Path(delivery_path).resolve()
    if not book_id or not root.is_dir():
        raise ValueError("请先生成包含公司教材编号的本地最终交付包。")
    files = [p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in {".jpg", ".jpeg", ".png", ".json", ".jsonl"}]
    if not files:
        raise ValueError("最终交付目录中没有可上传文件。")
    base_url = _base_url(server_url)
    token = _request_json(base_url + "/api/login", "POST", {"username": username, "password": password}, timeout=30)["token"]
    total = 0
    for path in sorted(files):
        content = path.read_bytes()
        if len(content) > 64 * 1024 * 1024:
            raise ValueError(f"单文件超过 64 MB：{path.name}")
        _request_json(base_url + "/api/deliveries/files", "POST", {"book": {"id": book_id}, "relative_path": path.relative_to(root).as_posix(), "content_base64": base64.b64encode(content).decode("ascii"), "sha256": hashlib.sha256(content).hexdigest()}, token, timeout=300)
        total += len(content)
    return {"book_id": book_id, "file_count": len(files), "bytes": total}


def pull_review_decisions(server_url: str, username: str, password: str, submission_id: str, project_path: str | Path) -> dict:
    """Fetch decisions only when they belong to the unchanged local snapshot."""
    base_url = _base_url(server_url)
    login = _request_json(base_url + "/api/login", "POST", {"username": username, "password": password}, timeout=30)
    document = _request_json(base_url + f"/api/submissions/{submission_id}/decisions", token=login["token"], timeout=30)["document"]
    current = build_review_snapshot(project_path, include_previews=False)
    if document.get("snapshot_fingerprint") != current["snapshot_fingerprint"]:
        raise ValueError("本地教材框或页面已变更，不能把旧审核结论覆盖到新版本。请重新提交审核。")
    target = Path(project_path).resolve().with_name(DECISIONS_FILENAME)
    temporary = target.with_suffix(target.suffix + ".tmp")
    temporary.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, target)
    return {"decision_path": str(target), "decision_count": len(document.get("decisions", [])), "submission_id": submission_id}
