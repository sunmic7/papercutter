def push_project_snapshot(server_url: str, username: str, password: str, project_path: str | Path,
                          *, token: str = "", review_snapshot: dict | None = None) -> dict:
    """Push the locally edited project back as the next server revision.

    The local ``project_revision`` is the base the edits were made on; the
    server stores ``stored + 1`` and returns it so the caller can reconcile.
    When ``review_snapshot`` is supplied the server creates the replacement
    review task (with its frozen project) inside the very same transaction, so
    a dropped connection can never leave the book without a live task.
    """
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    base_revision = int(project.get("online_review_base_revision", project.get("project_revision", 0)) or 0)
    document = build_project_sync_snapshot(project_path)
    document["base_revision"] = base_revision
    if isinstance(review_snapshot, dict):
        document["review_snapshot"] = review_snapshot
    base_url = _base_url(server_url)
    token = _login(base_url, username, password, token=token)
    result = _request_json(base_url + "/api/projects/sync", "POST", document, token, timeout=300)
    return {
        "book_id": result["project"].get("book_id", document["book"]["id"]),
        "base_revision": base_revision,
        "project_revision": int(result["project"].get("project_revision", 0) or 0),
        "server_relative_path": result["project"].get("server_relative_path", ""),
        "submission": result["project"].get("submission"),
    }


def _login(base_url: str, username: str, password: str, *, token: str = "") -> str:
    if token:
        return token
    return str(_request_json(base_url + "/api/login", "POST", {"username": username, "password": password}, timeout=30)["token"])


def collect_project_source_images(project_path: str | Path) -> list[tuple[str, Path]]:
    """Return ``(server_relative_path, absolute_path)`` for every page scan used.

    Only the images the project actually references are collected, so a book
    folder full of unrelated scans is not uploaded wholesale.
    """
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    roots = [
        str(project.get("image_root") or ""),
        str(project.get("book_root") or ""),
        str(project.get("answer_image_root") or ""),
    ]
    collected: dict[str, Path] = {}
    for pages_key in ("pages", "answer_pages", "ignored_pages"):
        for page in project.get(pages_key) or []:
            if not isinstance(page, dict):
                continue
            # A rotated page is read from ``rotated_image`` instead of
            # ``image`` by the review fingerprint and by the final cropper.
            # It must travel with the scans too, otherwise the server can
            # reproduce neither of them for that page.
            for field in ("image", "rotated_image"):
                image = str(page.get(field) or "").strip()
                if not image:
                    continue
                relative = image.replace("\\", "/").lstrip("/")
                if not relative or relative in collected:
                    continue
                for root in roots:
                    if not root:
                        continue
                    candidate = Path(root) / image
                    if candidate.is_file():
                        collected[relative] = candidate
                        break
    return sorted(collected.items())


def _source_inventory(base_url: str, token: str, book_id: str) -> list[dict]:
    document = _request_json(base_url + f"/api/projects/{book_id}/source-files", token=token, timeout=120)
    files = (document.get("source") or {}).get("files") or []
    return [item for item in files if isinstance(item, dict)]


def upload_project_source_images(
    server_url: str,
    username: str,
    password: str,
    project_path: str | Path,
    progress=None,
    force: bool = False,
    token: str = "",
) -> dict:
    """Upload the page scans the SERVER needs for review and final cropping.

    A reviewer also downloads these scans to redraw frames locally, but they
    are equally the source of the final delivery crops: employee workstations
    strip their local ``image_root`` before syncing, so the server can only
    reproduce the review fingerprint and render illustrations from this copy.
    Files already present with a matching size are skipped, so a resubmit after
    a few changed pages only transfers what is missing.
    """
    base_url = _base_url(server_url)
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    book_id = str(project.get("delivery_book_id", "")).strip()
    if not book_id:
        raise ValueError("本地工程缺少公司教材编号，不能上传原书图片。")
    pairs = collect_project_source_images(project_path)
    if not pairs:
        return {"book_id": book_id, "total": 0, "uploaded": 0, "skipped": 0, "bytes": 0}
    token = _login(base_url, username, password, token=token)
    existing = {} if force else {str(item.get("path", "")): int(item.get("bytes", 0) or 0)
                                 for item in _source_inventory(base_url, token, book_id)}
    pending: list[tuple] = []
    total_bytes = skipped = 0
    for index, (relative, absolute) in enumerate(pairs, start=1):
        if progress:
            progress(index, len(pairs), relative)
        size = absolute.stat().st_size
        if size > SOURCE_IMAGE_MAX_BYTES:
            raise ValueError(f"原书图片超过 {SOURCE_IMAGE_MAX_BYTES // (1024 * 1024)} MB，不能上传：{absolute.name}")
        if existing.get(relative) == size:
            skipped += 1
            continue
        pending.append((relative, absolute, size))
        total_bytes += size
    if pending:
        # 整本上传时逐张排队要等两百多个来回；改成原始二进制 + 四条连接并行。
        endpoint = base_url + f"/api/projects/{quote(str(book_id), safe='')}/source-file"
        jobs = [(endpoint + "?path=" + quote(relative, safe=""), token, absolute)
                for relative, absolute, _size in pending]
        try:
            _run_parallel(_binary_file_job, jobs)
        except RuntimeError:
            _upload_source_images_legacy(base_url, token, book_id, pending)
    return {"book_id": book_id, "total": len(pairs), "uploaded": len(pending), "skipped": skipped,
            "bytes": total_bytes}


def _upload_source_images_legacy(base_url: str, token: str, book_id: str, pending: list[tuple]) -> None:
    """Fallback for servers that predate the raw binary upload endpoint."""
    for relative, absolute, _size in pending:
        content = absolute.read_bytes()
        _request_json(
            base_url + f"/api/projects/{book_id}/source-files",
            "POST",
            {
                "relative_path": relative,
                "content_base64": base64.b64encode(content).decode("ascii"),
                "sha256": hashlib.sha256(content).hexdigest(),
            },
            token,
            timeout=600,
        )


def fetch_project_source_images(
    server_url: str,
    username: str,
    password: str,
    book_id: str,
    local_root: str | Path,
    progress=None,
    token: str = "",
) -> dict:
    """Download the page scans of one textbook into a local folder."""
    base_url = _base_url(server_url)
    safe_book_id = str(book_id or "").strip()
    if not safe_book_id or "/" in safe_book_id or "\\" in safe_book_id:
        raise ValueError("教材编号无效。")
    local_root = Path(local_root).expanduser().resolve()
    local_root.mkdir(parents=True, exist_ok=True)
    token = _login(base_url, username, password, token=token)
    inventory = _source_inventory(base_url, token, safe_book_id)
    downloaded = skipped = total_bytes = 0
    for index, item in enumerate(inventory, start=1):
        relative = str(item.get("path", "")).strip()
        if not relative:
            continue
        if progress:
            progress(index, len(inventory), relative)
        target = local_root / relative
        size = int(item.get("bytes", 0) or 0)
        if target.is_file() and target.stat().st_size == size:
            skipped += 1
            continue
        request = Request(
            base_url + f"/api/projects/{safe_book_id}/source-file?path={quote(relative, safe='/')}",
            headers={"Authorization": f"Bearer {token}"},
        )
        try:
            with urlopen(request, timeout=600) as response:
                content = response.read()
        except HTTPError as error:
            raise RuntimeError(f"下载原书图片失败（{relative}）：{error.code}") from error
        except URLError as error:
            raise RuntimeError(f"无法连接审核中心：{error.reason}") from error
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_name(target.name + ".downloading")
        temporary.write_bytes(content)
        os.replace(temporary, target)
        downloaded += 1
        total_bytes += len(content)
    return {"book_id": safe_book_id, "total": len(inventory), "downloaded": downloaded, "skipped": skipped, "bytes": total_bytes, "local_root": str(local_root)}
