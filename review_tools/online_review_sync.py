"""Client-side exchange with the PaperFlow online-review beta.

This module never calls a delivery exporter.  It creates a disposable review
snapshot from locally confirmed pages, uploads scaled page previews for human
inspection, and writes returned page decisions beside the local project.  The
actual cropped images and delivery JSON remain generated by PaperFlow locally.
"""

from __future__ import annotations

import base64
import gzip
import hashlib
import http.client
import json
import os
import threading
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlsplit
from urllib.request import Request, urlopen

from review_tools import manual_annotation_data as annotation_data


SCHEMA_VERSION = 1
DEFAULT_MAX_PREVIEW_SIDE = 1600
DECISIONS_FILENAME = "PaperFlow在线审核决定.json"
SOURCE_IMAGE_SUFFIXES = (".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tif", ".tiff")
SOURCE_IMAGE_MAX_BYTES = 48 * 1024 * 1024


class ReviewConflictError(RuntimeError):
    """The server rejected an upload because a newer snapshot revision exists."""


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _preview_cache_dir() -> Path:
    """Where generated page previews are reused from.

    Building one preview means decoding a full scan, resizing and re-encoding
    it (~120 ms per page on a fast PC).  Employees submit a book many times, so
    the JPEG is kept keyed by the file's content hash: unchanged pages cost one
    read instead of a full decode.
    """
    override = str(os.environ.get("PAPERFLOW_PREVIEW_CACHE") or "").strip()
    if override:
        return Path(override)
    base = (os.environ.get("LOCALAPPDATA") or os.environ.get("XDG_CACHE_HOME")
            or os.environ.get("TMPDIR") or "/tmp")
    return Path(base) / "PaperFlow" / "preview-cache"


def _preview_workers() -> int:
    override = str(os.environ.get("PAPERFLOW_PREVIEW_THREADS") or "").strip()
    if override.isdigit() and int(override) > 0:
        return min(16, int(override))
    return max(1, min(6, (os.cpu_count() or 4)))


def _cached_preview(cache_dir: Path, digest: str, side: int) -> tuple[bytes, int, int] | None:
    try:
        for candidate in cache_dir.glob(f"{digest}_{side}_*.jpg"):
            _, _, size = candidate.stem.split("_", 2)
            width, height = (int(part) for part in size.split("x"))
            return candidate.read_bytes(), width, height
    except (OSError, ValueError):
        return None
    return None


_PREVIEW_CACHE_LIMIT = 6000
_preview_pruned = False
_preview_prune_lock = threading.Lock()


def _store_preview(cache_dir: Path, digest: str, side: int, payload: bytes, width: int, height: int) -> None:
    global _preview_pruned
    try:
        cache_dir.mkdir(parents=True, exist_ok=True)
        target = cache_dir / f"{digest}_{side}_{width}x{height}.jpg"
        temporary = target.with_name(target.name + ".tmp")
        temporary.write_bytes(payload)
        os.replace(temporary, target)
        if not _preview_pruned:
            with _preview_prune_lock:
                if not _preview_pruned:
                    _preview_pruned = True
                    _prune_preview_cache(cache_dir)
    except OSError:
        pass  # 缓存失败只影响下次速度，不能挡住提交


def _prune_preview_cache(cache_dir: Path) -> None:
    """Keep the preview cache bounded (每台机器只做一次，代价可忽略)。"""
    try:
        files = [path for path in cache_dir.glob("*.jpg") if path.is_file()]
        if len(files) <= _PREVIEW_CACHE_LIMIT:
            return
        stamped = []
        for path in files:
            try:
                stamped.append((path.stat().st_mtime, path))
            except OSError:
                continue
        stamped.sort(reverse=True)
        for _mtime, path in stamped[_PREVIEW_CACHE_LIMIT:]:
            try:
                path.unlink()
            except OSError:
                pass
    except OSError:
        pass


def _page_entries(project: dict, max_preview_side: int, include_previews: bool,
                  previews_out: dict | None = None) -> list[dict]:
    """Build review page entries, generating previews in parallel.

    ``previews_out`` receives ``{page_key: jpeg_bytes}`` so the caller can push
    the previews as raw binary instead of stuffing base64 into one huge JSON.
    """
    try:
        import cv2
        import numpy as np
    except ImportError as error:  # pragma: no cover - installed with PaperFlow
        raise RuntimeError("本机缺少 OpenCV，无法生成审核预览。") from error
    candidates: list[dict] = []
    for kind, pages_key, records_key, answer in (
        ("question", "pages", "questions", False),
        ("answer", "answer_pages", "answers", True),
    ):
        for page_index, page in enumerate(project.get(pages_key, [])):
            # A review submission is deliberately a snapshot of confirmed work,
            # rather than a live copy of draft frames that may still change.
            if str(page.get("status", "")) != "accepted":
                continue
            regions = []
            for record in page.get(records_key, []):
                if not isinstance(record, dict):
                    continue
                # 续框（跨页续题片段）也要进审核快照：审核员在网站上必须能看到它，
                # 否则一份跨页题目在网站上只剩半截，审核结论会漏掉这半截。
                role = str(record.get("region_role", "question"))
                if role not in ("question", "continuation"):
                    continue
                bbox = record.get("bbox")
                if not (isinstance(bbox, (list, tuple)) and len(bbox) == 4):
                    continue
                region = {
                    "id": str(record.get("id", "")),
                    "display_number": annotation_data.display_number(record),
                    "bbox": [int(round(float(value))) for value in bbox],
                }
                if role == "continuation":
                    region["role"] = "continuation"
                    source_id = str(record.get("continuation_of", "") or "")
                    if source_id:
                        region["continuation_of"] = source_id
                regions.append(region)
            if not regions:
                continue
            candidates.append({
                "kind": kind,
                "page_index": page_index,
                "page_key": f"{kind}-{page_index}",
                "source": annotation_data.source_path(project, page, answer),
                "image_name": str(page.get("image", "")),
                "regions": regions,
            })
    if not candidates:
        return []
    cache_dir = _preview_cache_dir() if include_previews else None
    side = max(480, int(max_preview_side))

    def render(candidate: dict) -> dict:
        source = candidate["source"]
        path = Path(source)
        # Read once: the same bytes feed the fingerprint and the decoder. The
        # old version read every scan twice (once for SHA-256, once for
        # OpenCV), which alone cost a quarter of the submit time.
        try:
            raw = path.read_bytes()
        except OSError as error:
            raise ValueError(f"无法读取本地页面，不能提交审核：{source}") from error
        digest = hashlib.sha256(raw).hexdigest()
        payload: bytes = b""
        if include_previews:
            cached = _cached_preview(cache_dir, digest, side)
            if cached:
                payload, width, height = cached
            else:
                # cv2.imread is unreliable on Windows when the textbook path
                # has Chinese characters; decode from the bytes already read.
                image = cv2.imdecode(np.frombuffer(raw, dtype=np.uint8), cv2.IMREAD_COLOR)
                if image is None:
                    raise ValueError(f"无法读取本地页面，不能提交审核：{source}")
                height, width = image.shape[:2]
                scale = min(1.0, float(side) / max(width, height))
                if scale < 1.0:
                    image = cv2.resize(
                        image,
                        (max(1, round(width * scale)), max(1, round(height * scale))),
                        interpolation=cv2.INTER_AREA)
                ok, encoded = cv2.imencode(".jpg", image, [int(cv2.IMWRITE_JPEG_QUALITY), 78])
                if not ok:
                    raise RuntimeError(f"无法压缩审核预览：{source}")
                payload = encoded.tobytes()
                _store_preview(cache_dir, digest, side, payload, width, height)
        else:
            image = cv2.imdecode(np.frombuffer(raw, dtype=np.uint8), cv2.IMREAD_COLOR)
            if image is None:
                raise ValueError(f"无法读取本地页面，不能提交审核：{source}")
            height, width = image.shape[:2]
        item = {
            "page_key": candidate["page_key"],
            "kind": candidate["kind"],
            "page_index": candidate["page_index"],
            "image_name": candidate["image_name"] or path.name,
            "width": int(width),
            "height": int(height),
            "source_sha256": digest,
            "regions": candidate["regions"],
        }
        if include_previews:
            if previews_out is not None:
                # 调用方会把它当成二进制单独上传，没必要再额外持有一份 base64。
                previews_out[candidate["page_key"]] = payload
            else:
                item["preview"] = "data:image/jpeg;base64," + base64.b64encode(payload).decode("ascii")
        return item

    if len(candidates) == 1:
        return [render(candidates[0])]
    # 一本 150 页的书串行生成要 18 秒以上（员工机器更慢）。解码、缩放、编码
    # 都能并行，实测 4 线程 3.8 倍、8 线程 5.5 倍。
    from concurrent.futures import ThreadPoolExecutor
    workers = min(_preview_workers(), len(candidates))
    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(render, candidates))



def _review_content(project: dict) -> dict:
    """Approval binds to deliverable content, independent of local roots/autosaves."""
    book_keys = ("language", "stage", "grade", "subject", "answer_mode", "difficulty_scheme")
    record_keys = (
        "id", "bbox", "text", "question", "answer", "analysis", "options",
        "question_type", "difficulty", "knowledge_points", "number_path",
        "major_number", "minor_number", "subsection_number", "number_levels",
        "major_title", "subsection_title", "region_role", "continuation_of",
        "context", "context_ref", "shared_context", "shared_context_ids",
        "shared_context_boxes", "shared_context_segments", "parent_id", "continuations", "illustrations", "illustration_boxes",
        "image_areas", "match_scope_id", "answer_slots", "answer_granularity",
    )
    result = {key: project.get(key) for key in book_keys}
    result["pairs"] = [{key: pair.get(key) for key in ("question_id", "answer_ids", "status")}
                       for pair in project.get("pairs", [])]
    for pages_key, records_key in (("pages", "questions"), ("answer_pages", "answers")):
        result[pages_key] = [
            {"image": page.get("image"), "status": page.get("status"), "rotation": page.get("rotation", 0),
             "records": [{key: record.get(key) for key in record_keys} for record in page.get(records_key, [])]}
            for page in project.get(pages_key, [])
        ]
    return result


def content_fingerprint(project: dict) -> str:
    """Hash only what the review approves: deliverable content.

    Autosaves bump ``project_revision`` even when nothing a reviewer can see
    has changed (a page switch, a re-save of the same frames).  Comparing this
    digest lets the server keep a freshly submitted review task alive instead
    of marking it "resubmit" on the very next save.
    """
    if not isinstance(project, dict):
        return ""
    return hashlib.sha256(_canonical_json(_review_content(project))).hexdigest()


def project_book_name(project: dict, project_path: str | Path) -> str:
    """Retain the original title when a project is stored under its generated ID."""
    from pathlib import PureWindowsPath
    metadata = project.get("book_metadata") if isinstance(project.get("book_metadata"), dict) else {}
    book_id = str(project.get("delivery_book_id") or project.get("server_book_id") or "")
    roots = [project.get("book_root"), project.get("image_root"), str(Path(project_path).parent)]
    candidates = [metadata.get("book_name"), project.get("source_book_name"), project.get("book_name"),
                  *[PureWindowsPath(str(root)).name for root in roots if root]]
    return next((str(name).strip() for name in candidates if str(name or "").strip()
                 and str(name).strip().casefold() != book_id.casefold()), book_id)


def build_review_snapshot(project_path: str | Path, max_preview_side: int = DEFAULT_MAX_PREVIEW_SIDE, *,
                          include_previews: bool = True, previews_out: dict | None = None) -> dict:
    """Build a review-only document without touching any delivery output.

    ``previews_out`` is filled with ``{page_key: jpeg_bytes}`` so the caller can
    upload previews as binary instead of inlining megabytes of base64.
    """
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    pages = _page_entries(project, max(480, int(max_preview_side)), include_previews, previews_out)
    if not pages:
        raise ValueError("没有包含题框的已确认页面，无法提交审核。")
    book_id = str(project.get("delivery_book_id", "")).strip() or hashlib.sha256(str(project_path).encode("utf-8")).hexdigest()[:20]
    identity_pages = [{key: value for key, value in page.items() if key != "preview"} for page in pages]
    fingerprint = hashlib.sha256(_canonical_json({"book_id": book_id, "pages": identity_pages,
                                                 "content": _review_content(project)})).hexdigest()
    return {
        "schema_version": SCHEMA_VERSION,
        "kind": "paperflow_page_review_snapshot",
        "book": {"id": book_id, "name": project_book_name(project, project_path)},
        "project_revision": int(project.get("project_revision", 0)),
        "snapshot_fingerprint": fingerprint,
        # 内容指纹：只覆盖"审核能看到的东西"，保存时用它判断快照是否真的过期。
        "content_fingerprint": content_fingerprint(project),
        "pages": pages,
        "notice": "仅为审核预览，不含最终交付物；最终裁图和最终 JSON 由服务器在逐页审核通过后统一生成。",
    }


def _read_response_body(response) -> bytes:
    raw = response.read()
    if str(response.headers.get("Content-Encoding") or "").lower() == "gzip":
        return gzip.decompress(raw)
    return raw


def _request_json(url: str, method: str = "GET", payload: dict | None = None, token: str = "", timeout: int = 120) -> dict:
    headers = {"Accept": "application/json", "Accept-Encoding": "gzip"}
    body = None
    if payload is not None:
        body = _canonical_json(payload)
        headers["Content-Type"] = "application/json; charset=utf-8"
        # 工程快照和审核快照都是大段重复的 JSON 文本，压一遍再发能省七成流量。
        if len(body) > 256 * 1024:
            body = gzip.compress(body, 5)
            headers["Content-Encoding"] = "gzip"
    if token:
        headers["Authorization"] = f"Bearer {token}"
    try:
        data = _send_json(url, method, body, headers, timeout)
    except _GzipRejected:
        # 老服务器不认 Content-Encoding: gzip。退回明文重发一次，慢一点但能通。
        headers.pop("Content-Encoding", None)
        data = _send_json(url, method, _canonical_json(payload) if payload is not None else None,
                          headers, timeout)
    if not isinstance(data, dict) or not data.get("ok"):
        raise RuntimeError(str(data.get("error", "审核中心响应无效")) if isinstance(data, dict) else "审核中心响应无效")
    return data


class _GzipRejected(Exception):
    """Raised when the server refuses a gzip-encoded request body."""


def _send_json(url: str, method: str, body: bytes | None, headers: dict, timeout: int) -> dict:
    request = Request(url, data=body, headers=headers, method=method)
    try:
        with urlopen(request, timeout=timeout) as response:
            return json.loads(_read_response_body(response).decode("utf-8"))
    except HTTPError as error:
        raw_detail = b""
        try:
            raw_detail = _read_response_body(error)
        except OSError:
            pass
        detail = raw_detail.decode("utf-8", errors="replace")
        try:
            detail = json.loads(detail).get("error", detail)
        except json.JSONDecodeError:
            pass
        if error.code == 400 and headers.get("Content-Encoding") == "gzip":
            raise _GzipRejected(detail) from error
        if error.code == 409:
            raise ReviewConflictError(detail) from error
        raise RuntimeError(f"审核中心拒绝请求：{detail}") from error
    except URLError as error:
        raise RuntimeError(f"无法连接审核中心：{error.reason}") from error


def _base_url(value: str) -> str:
    value = str(value or "").strip().rstrip("/")
    if not value.startswith(("http://", "https://")):
        raise ValueError("审核中心地址必须以 http:// 或 https:// 开头。")
    return value


def _binary_post(url: str, token: str, digest: str, payload: bytes, timeout: int = 180) -> dict:
    """POST raw bytes with a SHA-256 header, skipping base64/JSON entirely.

    Base64 inflates a page scan by a third and makes the server build a huge
    string before it can write the file.  Sending the bytes straight through
    also lets several pages travel at once on separate connections.
    """
    parts = urlsplit(url)
    if parts.scheme == "https":
        connection = http.client.HTTPSConnection(parts.hostname, parts.port or 443, timeout=timeout)
    else:
        connection = http.client.HTTPConnection(parts.hostname, parts.port or 80, timeout=timeout)
    target = parts.path + (f"?{parts.query}" if parts.query else "")
    headers = {
        "Content-Type": "application/octet-stream",
        "Content-Length": str(len(payload)),
        "Authorization": f"Bearer {token}",
        "X-Paperflow-Sha256": digest,
        "Accept": "application/json",
        "Accept-Encoding": "gzip",
    }
    try:
        connection.request("POST", target, body=payload, headers=headers)
        response = connection.getresponse()
        raw = response.read()
        status = response.status
    except OSError as error:
        raise RuntimeError(f"无法连接审核中心：{error}") from error
    finally:
        connection.close()
    try:
        data = json.loads(raw.decode("utf-8")) if raw else {}
    except ValueError:
        data = {}
    if status >= 400 or not isinstance(data, dict) or not data.get("ok"):
        detail = data.get("error", "") if isinstance(data, dict) else ""
        raise RuntimeError(f"审核中心拒绝请求：{detail or f'HTTP {status}'}")
    return data


def _run_parallel(func, items: list[tuple], workers: int = 4) -> None:
    """Run ``func(*item)`` for every item on a small thread pool.

    Sequential uploads made a 150-page book wait for 150 round trips; four
    connections in flight cut that to roughly a quarter.  The first failure is
    re-raised so a half-finished upload can be retried instead of silently
    producing a review task with missing pages.
    """
    if not items:
        return
    from concurrent.futures import ThreadPoolExecutor
    if len(items) <= 1 or workers <= 1:
        for item in items:
            func(*item)
        return
    with ThreadPoolExecutor(max_workers=min(workers, len(items))) as pool:
        for future in [pool.submit(func, *item) for item in items]:
            future.result()


def _binary_bytes_job(url: str, token: str, digest: str, payload: bytes) -> None:
    _binary_post(url, token, digest, payload)


def _binary_file_job(url: str, token: str, path) -> None:
    # 读文件放在工作线程里：整本书 200 张 × 3 MB 全读进内存会直接把工作站拖死。
    content = Path(path).read_bytes()
    _binary_post(url, token, hashlib.sha256(content).hexdigest(), content)


def build_project_sync_snapshot(project_path: str | Path) -> dict:
    """Build the account-owned project document sent to the company server.

    This contains annotation records, but strips the local textbook locations.
    It is separate from review previews and is never a final-delivery export.
    """
    project_path = Path(project_path).resolve()
    project = annotation_data.load_project(project_path)
    # Round-trip through JSON to avoid mutating the in-memory project that the
    # desktop bridge is currently using.
    portable = json.loads(json.dumps(project, ensure_ascii=False))
    for key in ("book_root", "image_root", "answer_image_root"):
        portable.pop(key, None)
    book_id = str(portable.get("delivery_book_id", "")).strip()
    if not book_id:
        raise ValueError("本地工程缺少公司教材编号，不能同步到员工目录。")
    book_name = project_book_name(project, project_path)
    portable["source_book_name"] = book_name
    document = {
        "schema_version": SCHEMA_VERSION,
        "kind": "paperflow_project_sync",
        "book": {"id": book_id, "name": book_name},
        "project": portable,
    }
    if "online_review_base_revision" in project:
        document["base_revision"] = int(project["online_review_base_revision"])
    return document


def stage_submission_previews(base_url: str, token: str, book_id: str, snapshot: dict,
                              previews: dict, workers: int = 4) -> bool:
    """Push preview JPEGs as binary and shrink the submission payload.

    Returns ``False`` when the server has no staging endpoint (older build), so
    the caller can fall back to the original inline-base64 submission.
    """
    if not previews or not snapshot.get("pages"):
        return True
    endpoint = base_url + f"/api/projects/{quote(str(book_id), safe='')}/page-previews"
    try:
        existing = set(
            str(item) for item in
            (_request_json(endpoint, token=token, timeout=60)["previews"]["sha256"]))
    except (RuntimeError, KeyError, TypeError):
        return False
    digests: dict[str, str] = {}
    jobs: list[tuple] = []
    for page in snapshot["pages"]:
        payload = previews.get(page["page_key"])
        if not payload:
            continue
        digest = hashlib.sha256(payload).hexdigest()
        digests[page["page_key"]] = digest
        if digest not in existing:
            jobs.append((endpoint, token, digest, payload))
    if jobs:
        _run_parallel(_binary_bytes_job, jobs, workers)
    snapshot["page_previews"] = digests
    for page in snapshot["pages"]:
        # 预览已经单独传上去了，JSON 里一个字节都不该再带。
        page.pop("preview", None)
    return True


def submit_review_snapshot(server_url: str, username: str, password: str, project_path: str | Path, max_preview_side: int = DEFAULT_MAX_PREVIEW_SIDE, *, token: str = "") -> dict:
    """Sync the employee project, then upload review evidence; never final outputs."""
    base_url = _base_url(server_url)
    login = {"token": _login(base_url, username, password, token=token)}
    # Validate/read local evidence before advancing the remote project version.
    previews: dict[str, bytes] = {}
    snapshot = build_review_snapshot(project_path, max_preview_side, include_previews=True,
                                     previews_out=previews)
    project_sync = _request_json(
        base_url + "/api/projects/sync", "POST", build_project_sync_snapshot(project_path), login["token"], timeout=300
    )
    # A later submission/image request can fail independently. Remember the
    # successful sync immediately so retry does not conflict with our own write.
    local = annotation_data.load_project(project_path)
    local["online_review_base_revision"] = int(project_sync["project"]["project_revision"])
    annotation_data.save_project(local, project_path, increment_revision=False)
    book_id = str((snapshot.get("book") or {}).get("id") or "")
    staged = stage_submission_previews(base_url, login["token"], book_id, snapshot, previews)
    if not staged:
        # 老服务器没有中转区接口：退回原来的内联 base64，慢但能提交。
        for page in snapshot["pages"]:
            payload = previews.get(page["page_key"])
            if payload:
                page["preview"] = "data:image/jpeg;base64," + base64.b64encode(payload).decode("ascii")
    result = _request_json(base_url + "/api/submissions", "POST", snapshot, login["token"], timeout=300)
    return {
        "submission": result["submission"],
        "project": project_sync["project"],
        "snapshot_fingerprint": snapshot["snapshot_fingerprint"],
        "page_count": len(snapshot["pages"]),
        "previews_staged": staged,
    }


def upload_final_delivery(server_url: str, username: str, password: str, project_path: str | Path, delivery_path: str | Path, *, token: str = "") -> dict:
    """Atomically publish a locally generated final package.

    The complete manifest is accepted before any content is uploaded.  Content
    goes to a server-side staging folder and becomes visible only after every
    file passes its byte and SHA-256 checks.
    """
    project = annotation_data.load_project(Path(project_path).resolve())
    book_id = str(project.get("delivery_book_id", "")).strip()
    root = Path(delivery_path).resolve()
    if not book_id or not root.is_dir():
        raise ValueError("请先生成包含公司教材编号的本地最终交付包。")
    files = [p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in {".jpg", ".jpeg", ".png", ".json", ".jsonl"}]
    if not files:
        raise ValueError("最终交付目录中没有可上传文件。")
    prepared = []
    total = 0
    for path in sorted(files):
        content = path.read_bytes()
        if not content:
            raise ValueError(f"最终交付包含空文件，未上传任何文件：{path.relative_to(root).as_posix()}")
        if len(content) > 64 * 1024 * 1024:
            raise ValueError(f"单文件超过 64 MB：{path.name}")
        prepared.append((path, content, hashlib.sha256(content).hexdigest()))
        total += len(content)
    base_url = _base_url(server_url)
    token = _login(base_url, username, password, token=token)
    manifest = [{"relative_path": path.relative_to(root).as_posix(), "bytes": len(content), "sha256": digest}
                for path, content, digest in prepared]
    batch = _request_json(base_url + "/api/deliveries/batches", "POST", {"book": {"id": book_id}, "files": manifest}, token, timeout=300)["batch"]
    batch_id = str(batch["batch_id"])
    for path, content, _digest in prepared:
        _request_json(base_url + f"/api/deliveries/batches/{batch_id}/files", "POST", {
            "relative_path": path.relative_to(root).as_posix(),
            "content_base64": base64.b64encode(content).decode("ascii"),
        }, token, timeout=300)
    committed = _request_json(base_url + f"/api/deliveries/batches/{batch_id}/commit", "POST", {}, token, timeout=300)["delivery"]
    return {"book_id": book_id, "file_count": int(committed["file_count"]), "bytes": total, "batch_id": batch_id}


def pull_review_decisions(server_url: str, username: str, password: str, submission_id: str, project_path: str | Path, *, token: str = "") -> dict:
    """Fetch decisions only when they belong to the unchanged local snapshot."""
    base_url = _base_url(server_url)
    login = {"token": _login(base_url, username, password, token=token)}
    document = _request_json(base_url + f"/api/submissions/{submission_id}/decisions", token=login["token"], timeout=30)["document"]
    current = build_review_snapshot(project_path, include_previews=False)
    if document.get("snapshot_fingerprint") != current["snapshot_fingerprint"]:
        raise ValueError("本地教材框或页面已变更，不能把旧审核结论覆盖到新版本。请重新提交审核。")
    target = Path(project_path).resolve().with_name(DECISIONS_FILENAME)
    temporary = target.with_suffix(target.suffix + ".tmp")
    temporary.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, target)
    return {"decision_path": str(target), "decision_count": len(document.get("decisions", [])), "submission_id": submission_id}


